import React from 'react';
import { View, Text, StyleSheet } from '@react-pdf/renderer';
import { BRAND } from '../styles';
import { REPORT_TYPE_META } from '../types';
import { SectionHeading } from './PdfPrimitives';
import { PdfIcon } from './PdfIcon';
import type { ReportType, SignatureRole } from '../types';

const s = StyleSheet.create({
  section: { marginBottom: 18 },
  grid: { flexDirection: 'row' },
  lane: {
    flex: 1, marginRight: 12,
    backgroundColor: BRAND.white, borderWidth: 1, borderColor: BRAND.borderSoft,
    borderRadius: 8, padding: 12,
  },
  laneLast: {
    flex: 1,
    backgroundColor: BRAND.white, borderWidth: 1, borderColor: BRAND.borderSoft,
    borderRadius: 8, padding: 12,
  },
  roleRow: { flexDirection: 'row', alignItems: 'center', marginBottom: 26 },
  roleName: { fontSize: 9.5, fontFamily: 'Helvetica-Bold', color: BRAND.foreground, marginLeft: 6 },
  sigLine: { borderTopWidth: 1, borderTopColor: BRAND.foreground, paddingTop: 4 },
  dateLine: { fontSize: 8, color: BRAND.mutedForeground },
  note: { fontSize: 7.5, color: BRAND.mutedForeground, marginTop: 10, lineHeight: 1.5 },
});

const ROLE_LABELS: Record<SignatureRole, string> = {
  owner: 'Property Owner',
  tenant: 'Tenant',
  inspector: 'Reeve Inspector',
};

export function SignatureBlock({ reportType }: { reportType: ReportType }) {
  const roles = REPORT_TYPE_META[reportType].signatureRoles;
  const hasTenant = roles.includes('tenant');

  return (
    <View style={s.section} wrap={false}>
      <SectionHeading
        icon="signature" title="Sign-off" accent={BRAND.indigo}
        id="sec-signoff" bookmark="Sign-off"
      />
      <View style={s.grid}>
        {roles.map((role, i) => {
          const isLast = i === roles.length - 1;
          return (
            <View key={role} style={isLast ? s.laneLast : s.lane}>
              <View style={s.roleRow}>
                <PdfIcon name="user" size={11} color={BRAND.indigo} />
                <Text style={s.roleName}>{ROLE_LABELS[role]}</Text>
              </View>
              <View style={s.sigLine}>
                <Text style={s.dateLine}>Date: ________________</Text>
              </View>
            </View>
          );
        })}
      </View>
      <Text style={s.note}>
        {hasTenant
          ? 'This report was prepared by Reeve from observations recorded during the inspection walkthrough. The tenant acknowledges having reviewed the recorded condition of the property on the date shown above. This document is generated by Reeve.'
          : 'This report was prepared by Reeve from observations recorded during the inspection walkthrough. This document is generated by Reeve.'}
      </Text>
    </View>
  );
}
