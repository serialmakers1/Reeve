import React from 'react';
import { View, Text, StyleSheet } from '@react-pdf/renderer';
import { BRAND, styles } from '../styles';
import { REPORT_TYPE_META } from '../types';
import type { ReportType, SignatureRole } from '../types';

const s = StyleSheet.create({
  section: { marginTop: 8 },
  grid: { flexDirection: 'row', marginTop: 8 },
  box: {
    flex: 1,
    marginRight: 12,
    borderTopWidth: 1,
    borderTopColor: BRAND.foreground,
    paddingTop: 6,
  },
  boxLast: {
    flex: 1,
    borderTopWidth: 1,
    borderTopColor: BRAND.foreground,
    paddingTop: 6,
  },
  roleName: {
    fontSize: 9,
    fontWeight: 700,
    color: BRAND.foreground,
    marginBottom: 2,
  },
  dateLine: {
    fontSize: 8,
    color: BRAND.mutedForeground,
    marginTop: 24,
  },
  disclaimer: {
    fontSize: 7,
    color: BRAND.mutedForeground,
    marginTop: 12,
    lineHeight: 1.5,
  },
});

const ROLE_LABELS: Record<SignatureRole, string> = {
  owner:     'Property Owner',
  tenant:    'Tenant',
  inspector: 'Reeve Inspector',
};

interface Props {
  reportType: ReportType;
}

export function SignatureBlock({ reportType }: Props) {
  const roles = REPORT_TYPE_META[reportType].signatureRoles;
  return (
    <View style={s.section} wrap={false}>
      <Text style={styles.sectionHeader}>Signatures</Text>
      <View style={s.grid}>
        {roles.map((role, i) => {
          const isLast = i === roles.length - 1;
          return (
            <View key={role} style={isLast ? s.boxLast : s.box}>
              <Text style={s.roleName}>{ROLE_LABELS[role]}</Text>
              <Text style={s.dateLine}>Date: ________________</Text>
            </View>
          );
        })}
      </View>
      <Text style={s.disclaimer}>
        By signing above, the parties confirm that they have jointly inspected the premises and
        agree that this report accurately reflects the condition of the property at the time of
        inspection. This document is generated by Reeve Property Management Pvt. Ltd.
      </Text>
    </View>
  );
}
